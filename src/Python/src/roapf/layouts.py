"""Single-line-diagram layouts for the voltage temperature maps.

Coordinates are in figure pixels with y pointing down (as digitised); they are
flipped when drawn. The IEEE 14-bus layout follows Fig. 22.1 of F. Milano,
*Power System Modelling and Scripting* (Springer, 2010).

``bars``   bus number -> (x_start, y_start, x_end, y_end) of the bus bar
``lines``  (from bus, to bus) -> polyline [(x, y), ...] of the branch
``frame``  (x_min, y_min, x_max, y_max) of the map
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Layout:
    frame: tuple[float, float, float, float]
    bars: dict[int, tuple[float, float, float, float]]
    markers: dict[int, tuple[float, float]]
    lines: dict[tuple[int, int], list[tuple[float, float]]]
    outline: list[tuple[float, float]] = field(default_factory=list)  # e.g. a state boundary


